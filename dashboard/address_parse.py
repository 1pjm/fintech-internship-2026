def parse_sido(address: str) -> str | None:
    """주소 문자열에서 시도를 찾아 학습데이터 형식(2글자)으로 반환. 못 찾으면 None."""
    address = address.strip()
    for key in _SORTED_KEYS:
        if address.startswith(key) or re.search(rf"(^|\s){re.escape(key)}(\s|$)", address):
            return SIDO_ALIASES[key]
    for key, sido in SIGUNGU_TO_SIDO.items():
        if key in address:
            return sido
    return None


